// Generates src/lib/preview-fallbacks.generated.mjs — a safety-net preview for every
// @loomidev/* package, extracted straight from that package's README.md.
//
// ComponentsGalleryPage.astro's hand-curated PREVIEWS map is what actually ships on the
// cards today: someone looked at each component, picked a compact example, and scaled it
// to fit the fixed-height card slot. That curation doesn't disappear — the gallery page
// prefers PREVIEWS[name] first and only falls back to this generated map when a name is
// missing from it. So the day a new package lands in loomiui-packages.mjs with no
// hand-tuned entry yet, its card shows *something* live (not a blank slot) instead of
// silently rendering empty until a human gets around to curating it.
//
// Not a replacement for curation: the wrapper here is generic (fixed height, centered,
// scaled down) and has no per-component judgment — no picking a closed vs. open state,
// no swapping out a placeholder asset path that happens to render an error. Treat a
// fallback preview as a prompt to go hand-write a real PREVIEWS entry, the same way
// `fallbackReadme()` in gen-component-docs.mjs is a stopgap for a missing README.
//
//   node scripts/gen-preview-fallbacks.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { COMPONENT_NAMES } from "./loomiui-packages.mjs";

const PACKAGES = resolve(import.meta.dirname, "../../components/packages");
const OUT_FILE = resolve(import.meta.dirname, "../src/lib/preview-fallbacks.generated.mjs");

// Unlike gen-component-docs.mjs's withLivePreviews() — which renders a README's ```html
// fence in full, on its own doc page, paired with whatever ```js setup script sits next to
// it — this runs many components' markup side by side on one page. A README's own
// <script> (document.querySelector, getElementById, onclick globals like
// showLoomiModal(...)) is written assuming it's the only component on the page and would
// reach across cards or collide with another card using the same id/tag. So this strips
// <script> tags rather than executing them: the fallback only ever shows the component in
// its plain-markup default state, never README-scripted data.
function firstHtmlExample(readme) {
  const fenceRe = /```html(?:\.skip)?\n([\s\S]*?)\n```/g;
  let match;
  while ((match = fenceRe.exec(readme))) {
    const code = match[1];
    if (/type=["']importmap["']/.test(code)) continue;
    const withoutScripts = code.replace(/<script[\s\S]*?<\/script>/gi, "").trim();
    if (!withoutScripts) continue;
    return firstTopLevelElement(withoutScripts);
  }
  return null;
}

// Some READMEs show 2-3 variants of the same tag stacked in one fence (e.g. button's
// plain/uppercase/link-tag examples). A card has room for exactly one, so take the first
// complete top-level element and discard the rest, rather than cramming all of them in.
function firstTopLevelElement(html) {
  const openTagMatch = html.match(/<([a-zA-Z][a-zA-Z0-9-]*)/);
  if (!openTagMatch) return null;
  const tag = openTagMatch[1];
  const start = openTagMatch.index;

  const firstTagEndsSelfClosing = /^<[a-zA-Z][^>]*\/>/.test(html.slice(start));
  if (firstTagEndsSelfClosing) {
    const end = html.indexOf("/>", start) + 2;
    return html.slice(start, end);
  }

  // Deliberately two distinct alternatives rather than one `<\/?tag(?:[\s>][^>]*)?>` —
  // letting ">" itself kick off the "attributes" branch made `[^>]*` greedily swallow
  // past a bare `<tag>` into whatever ">" came next (e.g. a nested `<a href="#">`),
  // merging two separate tags into one bogus match.
  const tokenRe = new RegExp(`<\\/${tag}>|<${tag}(?:\\s[^>]*)?>`, "gi");
  tokenRe.lastIndex = start;
  let depth = 0;
  let match;
  while ((match = tokenRe.exec(html))) {
    if (match[0].startsWith("</")) {
      depth--;
      if (depth === 0) return html.slice(start, match.index + match[0].length);
    } else if (!match[0].endsWith("/>")) {
      depth++;
    }
  }
  // Unclosed (self-closing without the trailing slash, or a parse edge case) — fall back
  // to the rest of the fence rather than nothing.
  return html.slice(start).trim();
}

function genericWrapper(code) {
  return (
    `<div style="height:5.5rem;width:100%;overflow:hidden;display:flex;align-items:center;justify-content:center">` +
    `<div style="transform:scale(.7);transform-origin:center">${code}</div></div>`
  );
}

let written = 0;
let skipped = 0;
const entries = [];
for (const name of COMPONENT_NAMES) {
  let readme;
  try {
    readme = readFileSync(resolve(PACKAGES, name, "README.md"), "utf8");
  } catch {
    skipped++;
    continue;
  }
  const example = firstHtmlExample(readme);
  if (!example) {
    skipped++;
    continue;
  }
  entries.push([name, genericWrapper(example)]);
  written++;
}

const header = [
  "// GENERATED by scripts/gen-preview-fallbacks.mjs — do not hand-edit.",
  "// Safety-net card previews extracted from each package's README, used only for",
  "// components missing a hand-curated entry in ComponentsGalleryPage.astro's PREVIEWS.",
  "",
].join("\n");

// The JSDoc annotation gives this a `Record<string, string>` index signature — without
// it, TS infers a closed object-literal type from the JSON below (one fixed set of known
// keys), and indexing it with the `string`-typed `name` in ComponentsGalleryPage.astro
// fails to type-check (ts(7053): "no index signature ... was found").
const body = [
  "/** @type {Record<string, string>} */",
  `export const FALLBACK_PREVIEWS = ${JSON.stringify(Object.fromEntries(entries), null, 2)};`,
  "",
].join("\n");

writeFileSync(OUT_FILE, header + body);
console.log(`[gen-preview-fallbacks] wrote ${written} fallback previews (${skipped} skipped — no README/example found).`);
